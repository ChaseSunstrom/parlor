"""A tiny NES cartridge for the checks: nothing copyrighted, written here byte by byte."""


def nes_rom() -> bytes:
    """an NROM cartridge with battery memory: it paints the screen green (every colour of the first palette, so whatever
    the pattern memory starts with), then writes "PL" to its save, and idles"""
    code = bytes([
        0x78, 0xD8, 0xA2, 0x40, 0x8E, 0x17, 0x40, 0xA2, 0xFF, 0x9A, 0xE8,  # sei cld; ldx #$40 stx $4017; ldx #$ff txs; inx
        0x8E, 0x00, 0x20, 0x8E, 0x01, 0x20,  # stx $2000; stx $2001 (rendering off)
        0x2C, 0x02, 0x20, 0x10, 0xFB, 0x2C, 0x02, 0x20, 0x10, 0xFB,  # two vblank waits
        0xAD, 0x02, 0x20, 0xA9, 0x3F, 0x8D, 0x06, 0x20, 0xA9, 0x00, 0x8D, 0x06, 0x20,  # $2006 = $3F00
        0xA9, 0x2A, 0x8D, 0x07, 0x20, 0x8D, 0x07, 0x20, 0x8D, 0x07, 0x20, 0x8D, 0x07, 0x20,  # the first palette, all green
        0xA9, 0x00, 0x8D, 0x05, 0x20, 0x8D, 0x05, 0x20,  # scroll 0,0
        0xA9, 0x50, 0x8D, 0x00, 0x60, 0xA9, 0x4C, 0x8D, 0x01, 0x60,  # battery memory: "PL"
        0xA9, 0x0A, 0x8D, 0x01, 0x20,  # show the background
        0x4C, 0x00, 0x00,  # jmp to itself (patched below)
    ])
    prg = bytearray(code + bytes(16384 - len(code)))
    loop = 0xC000 + len(code) - 3
    prg[len(code) - 2:len(code)] = loop.to_bytes(2, "little")
    prg[len(code) - 1] = prg[len(code) - 1]
    rti = 0xC000 + len(code)  # the zero after the code is "brk"; vectors point NMI/IRQ at an rti we put there
    prg[len(code)] = 0x40
    prg[0x3FFA:0x4000] = rti.to_bytes(2, "little") + (0xC000).to_bytes(2, "little") + rti.to_bytes(2, "little")
    return b"NES\x1a" + bytes([1, 0, 0x02, 0]) + bytes(8) + bytes(prg)
